def detect_scenario_A(sentence):
    """
    Scenario A — Volitional/epistemic matrix verb + subordinate clause.

    Correctly handles modal chains (e.g. 'espero que pueda viajar'):
    if the direct dependent is an infinitive, checks for a modal auxiliary
    bearing the Mood feature.

    Coreferential infinitives (same subject) are discarded, not counted as Elision.
    Indicative after INDICATIVE_TRIGGER_VERBS is discarded (not a subjunctive context).
    Subjunctive after INDICATIVE_TRIGGER_VERBS = Hypercorrection.
    """
    cases = []
    for w in sentence.words:
        if w.upos not in ('VERB', 'AUX'):
            continue
        lemma = w.lemma.lower()
        is_volitional  = lemma in VOLITIONAL_VERBS
        is_ind_trigger = lemma in INDICATIVE_TRIGGER_VERBS
        if not (is_volitional or is_ind_trigger):
            continue

        # Collect all direct ccomp/xcomp dependents
        candidates = [
            c for c in sentence.words
            if c.head == w.id and c.upos in ('VERB', 'AUX')
            and c.deprel in ('ccomp', 'xcomp')
        ]
        if not candidates:
            continue

        v_sub     = candidates[0]
        verb_form = get_feat(v_sub.feats, 'VerbForm')
        mood      = get_feat(v_sub.feats, 'Mood')

        # Handle modal chains: if v_sub is bare infinitive, check for
        # an auxiliary (e.g. 'pueda') that carries the actual Mood
        if verb_form == 'Inf' and not mood:
            for aux in sentence.words:
                if aux.head == v_sub.id and aux.deprel == 'aux' and aux.upos == 'AUX':
                    mood_aux = get_feat(aux.feats, 'Mood')
                    if mood_aux in ('Sub', 'Ind'):
                        v_sub     = aux
                        verb_form = get_feat(aux.feats, 'VerbForm')
                        mood      = mood_aux
                        break

        target = None
        if is_volitional and verb_form == 'Inf':
            # Coreferential infinitive = grammatical, not an error
            target = 'Elision' if has_explicit_subject(v_sub, sentence) else None
        elif is_volitional and mood == 'Sub':
            target = 'Correct'
        elif is_volitional and mood == 'Ind':
            target = 'Indicative_Elision'
        elif is_ind_trigger and mood == 'Sub':
            target = 'Hipercorreccion'
        elif is_ind_trigger and mood == 'Ind':
            target = None   # indicative is the only correct option here

        if target:
            cases.append({
                'id_matrix_verb': w.id,
                'matrix_lemma'    : lemma,
                'matrix_type'    : 'Volition' if is_volitional else 'Indicative_Trigger',
                'id_sub_verb'   : v_sub.id,
                'sub_form'      : v_sub.text,
                'verb_form'      : verb_form,
                'mood'           : mood,
                'target_class'   : target
            })
    return cases


def detect_scenario_B(sentence):
    """
    Scenario B — Indefinite noun phrase or indefinite pronoun + relative clause.

    The relative clause verb should be in subjunctive (inespecific/hypothetical
    referent). Indicative in this context = Elision.

    Past-tense indicative relatives are excluded: if the event already occurred,
    the referent is specific and indicative is correct.
    """
    cases = []
    INDEFINITE_DETERMINERS = {
        'un', 'uno', 'una',
        'todo', 'toda', 'todos', 'todas',
        'cualquier', 'cualquiera',
        'algún', 'alguno', 'alguna', 'algunos', 'algunas',
        'ningún', 'ninguno', 'ninguna',
    }

    nucleus_candidates = []
    for w in sentence.words:
        if w.upos == 'NOUN':
            has_indef = any(
                d.head == w.id and d.deprel == 'det'
                and d.lemma.lower() in INDEFINITE_DETERMINERS
                for d in sentence.words
            )
            if has_indef:
                nucleus_candidates.append(w)
        elif w.upos == 'PRON' and w.lemma.lower() in INDEFINITE_PRONOUNS:
            nucleus_candidates.append(w)

    for nucleus in nucleus_candidates:
        for v_rel in sentence.words:
            if v_rel.head != nucleus.id or v_rel.deprel not in ('acl:relcl', 'acl'):
                continue
            if v_rel.upos not in ('VERB', 'AUX'):
                continue

            verb_form = get_feat(v_rel.feats, 'VerbForm')
            mood      = get_feat(v_rel.feats, 'Mood')
            tense     = get_feat(v_rel.feats, 'Tense')

            # Exclude past indicative: specific referent, indicative is correct
            if tense in ('Past', 'Imp') and mood == 'Ind':
                continue

            if verb_form == 'Inf':
                target = 'Elision'
            elif mood == 'Sub':
                target = 'Correct'
            elif mood == 'Ind':
                target = 'Indicative_Elision'
            else:
                continue

            cases.append({
                'id_matrix_verb': nucleus.id,
                'matrix_lemma'    : nucleus.lemma,
                'matrix_type'    : 'Indefinite_Relative',
                'id_sub_verb'   : v_rel.id,
                'sub_form'      : v_rel.text,
                'verb_form'      : verb_form,
                'mood'           : mood,
                'target_class'   : target
            })
    return cases

def detect_scenario_C(sentence):
    """
    Scenario C — Final/purpose conjunctions followed by verb.
    Subjunctive obligatory after all connectors in FINAL_CONNECTORS.
    Infinitive or indicative after them = Elision.
    """
    cases        = []
    words        = sentence.words
    tokens_lower = [w.text.lower() for w in words]

    for i, w in enumerate(words):
        connector_found = None
        connector_len   = 0
        for conn in FINAL_CONNECTORS:
            n = len(conn)
            if tokens_lower[i:i + n] == list(conn):
                connector_found = conn
                connector_len = n
                break

        if connector_found is None:
            continue

        next_idx = i + connector_len
        if next_idx >= len(words):
            continue

        v_sub = words[next_idx]
        if v_sub.upos not in ('VERB', 'AUX'):
            found = False
            for j in range(next_idx, min(next_idx + 3, len(words))):
                if words[j].upos in ('VERB', 'AUX'):
                    v_sub = words[j]
                    found = True
                    break
            if not found:
                continue

        verb_form = get_feat(v_sub.feats, 'VerbForm')
        mood      = get_feat(v_sub.feats, 'Mood')

        if verb_form == 'Inf':
            target = 'Elision'
        elif mood == 'Sub':
            target = 'Correct'
        elif mood == 'Ind':
            target = 'Indicative_Elision'
        else:
            continue


        cases.append({
            'id_matrix_verb': w.head,
            'matrix_lemma'    : ' '.join(connector_found),
            'matrix_type'    : 'Final_Conector',
            'id_sub_verb'    : v_sub.id,
            'sub_form'      : v_sub.text,
            'verb_form'      : verb_form,
            'mood'           : mood,
            'target_class'   : target
        })
    return cases

def detect_scenario_D(sentence):
    """
    Scenario D — Evaluative predicate (adjective/noun) + subordinate clause.
    e.g. 'es importante que', 'no soy partidaria de que'.

    Handles nested copular structures: if the direct dependent is a predicative
    adjective with its own copula, the copula carries the actual Mood.

    Coreferential infinitives (generic impersonal constructions such as
    'es fundamental cambiar') are excluded, not counted as Elision.
    """
    cases = []
    for w in sentence.words:
        if w.upos not in ('ADJ', 'NOUN'):
            continue
        if w.lemma.lower() not in EVALUATIVE_PREDICATES:
            continue

        v_sub = None
        for cand in sentence.words:
            if cand.head != w.id:
                continue
            if cand.upos in ('VERB', 'AUX') and cand.deprel in ('ccomp', 'csubj', 'advcl'):
                v_sub = cand
                break
            # Nested copular predicate: 'no soy partidaria de que esté casada'
            if cand.upos == 'ADJ' and cand.deprel == 'acl':
                for cop in sentence.words:
                    if cop.head == cand.id and cop.deprel == 'cop' and cop.upos == 'AUX':
                        v_sub = cop
                        break
                if v_sub:
                    break

        if v_sub is None:
            continue

        verb_form = get_feat(v_sub.feats, 'VerbForm')
        mood      = get_feat(v_sub.feats, 'Mood')

        target = None
        if verb_form == 'Inf':
          # Generic impersonal infinitive = grammatical, not an error
           target = 'Elision' if has_explicit_subject(v_sub, sentence) else None
        elif mood == 'Sub':
            target = 'Correct'
        elif mood == 'Ind':
            target = 'Indicative_Elision'

        if target:
            cases.append({
                'id_matrix_verb': w.id,
                'matrix_lemma'    : w.lemma,
                'matrix_type'    : 'Evaluative_Predicate',
                'id_sub_verb'   : v_sub.id,
                'sub_form'      : v_sub.text,
                'verb_form'      : verb_form,
                'mood'           : mood,
                'target_class'   : target
            })
    return cases

