def get_feat(feats_str, feature_name):
  """
  Extract the value of a UD morphological feature from a Stanza feats string.
  e.g. get_feat('Mood=Sub|Number=Sing', 'Mood') -> 'Sub'
  """
  if not feats_str:
    return ''
  for feat in feats_str.split('|'):
      if feat.startswith(feature_name + '='):
        return feat.split('=')[1]
  return ''

def has_explicit_subject(v_sub, sentence):
    """
    Return True if the subordinate verb has its own explicit subject (nsubj),
    indicating a subject change relative to the matrix verb.
    Return False if the subject is likely coreferential (implicit, same subject).
    Coreferential infinitives are grammatically correct and should not be
    counted as elision errors.
    """
    return any(
        cand.head == v_sub.id and cand.deprel in ('nsubj', 'nsubj:pass')
        for cand in sentence.words
    )

