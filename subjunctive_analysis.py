def calculate_dsi(sentence, id_matrix_verb, id_sub_verb):
    """
    Interverbal Syntactic Distance (DSI) between two verbs.

    Returns:
        linear_distance      (DL): linear token distance between the two verbs
        syntactic_depth (PS): graph distance in the dependency tree (BFS)

    Based on Liu (2008) — Mean Dependency Distance as a measure of
    syntactic processing complexity.
    """
    DL = max(0, abs(id_sub_verb - id_matrix_verb) - 1)

    graph = {w.id: [] for w in sentence.words}
    graph[0] = []
    for w in sentence.words:
        graph[w.id].append(w.head)
        graph.setdefault(w.head, []).append(w.id)

    visited = {id_matrix_verb}
    queue   = deque([(id_matrix_verb, 0)])
    PS      = -1
    while queue:
        node, dist = queue.popleft()
        if node == id_sub_verb:
            PS = dist
            break
        for neighbour in graph.get(node, []):
            if neighbour not in visited:
                visited.add(neighbour)
                queue.append((neighbour, dist + 1))

    return {'linear_distance': DL, 'syntactic_depth': PS}


def calculate_mdd(sentence):
    """Mean Dependency Distance (MDD for the ful sentence (Liu, 2008)."""
    distances = [abs(w.id - w.head) for w in sentence.words if w.head != 0]
    return sum(distances) / len(distances) if distances else 0.0

