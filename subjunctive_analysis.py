def score_to_cefr(score):
    """Map CEDEL2 placement test score (0-43) to proficiency band."""
    if score is None:
        return 'UNKNOWN'
    if 0  <= score <= 12: return 'lower_beginner'
    if 13 <= score <= 20: return 'upper_beginner'
    if 21 <= score <= 28: return 'lower_intermediate'
    if 29 <= score <= 35: return 'upper_intermediate'
    if 36 <= score <= 40: return 'lower_advanced'
    if 41 <= score <= 43: return 'upper_advanced'
    return 'UNKNOWN'


def parse_cedel2_txt(filename, content_bytes):
    """
    Parse a CEDEL2 TXT file from its filename and raw bytes.
    Expected filename format: L1_TASKTYPE_SCORE_AGE_YEARS_NTASK_SUBJECTID.txt
    e.g. EN_WR_41_22_7_1_DLM.txt
    """
    stem  = os.path.splitext(os.path.basename(filename))[0]
    parts = stem.split('_')
    text  = content_bytes.decode('utf-8', errors='replace').strip()

    if len(parts) < 7:
        return {
            'subject_id': stem, 'l1': 'UNKNOWN', 'task_type': 'UNKNOWN',
            'score': None, 'CEFR_level': 'UNKNOWN', 'age': None,
            'years_of_study': None, 'task_num': None, 'text': text
        }

    def safe_int(val):
      try:    return int(float(val))
      except: return None


    score = safe_int(parts[2])
    return {
        'subject_id'    : '_'.join(parts[6:]),
        'l1'           : parts[0],
        'task_type'  : parts[1],
        'score'        : score,
        'CEFR_level'   : score_to_cefr(score),
        'age'         : safe_int(parts[3]),
        'years_of_study': safe_int(parts[4]),
        'task_num'    : safe_int(parts[5]),
        'text'        : text
      }


