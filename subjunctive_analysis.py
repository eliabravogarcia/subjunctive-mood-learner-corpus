def process_document(doc_dict, nlp_pipeline):
    """
    Run all four scenario detectors over a single corpus document.
    Returns a list of case dictionaries with DSI and MDD metrics.
    """
    subject_id = doc_dict['subject_id']
    cefr_level = doc_dict['CEFR_level']
    text       = doc_dict['text']

    if not text or not text.strip():
        return []

    try:
        doc = nlp_pipeline(text)
    except Exception as exc:
        print(f'\n⚠️  Error processing {subject_id}: {exc}')
        return []

    rows = []
    for sentence in doc.sentences:
        detectors = [
            detect_scenario_A(sentence),
            detect_scenario_B(sentence),
            detect_scenario_C(sentence),
            detect_scenario_D(sentence),
        ]
        for cases in detectors:
            for case in cases:
              dsi = calculate_dsi(
                  sentence,
                  case['id_matrix_verb'],
                  case['id_sub_verb']
              )
              mdd = calculate_mdd(sentence)

              matrix_type = case['matrix_type']
              if matrix_type in ('Volition', 'Final_Conector',
                                 'Indefinite_Relative', 'Evaluative_Predicate'):
                model = 'M1_elision'
              elif matrix_type == 'Indicative_Trigger':
                model = 'M2_hypercorrection'
              else:
                model = 'UNKNOWN'

              rows.append({
                    'ID_Subject'          : subject_id,
                    'Model'               : model,
                    'CEFR_Level'          : cefr_level,
                    'Matrix_Type'         : case['matrix_type'],
                    'Trigger_Lemma'       : case['matrix_lemma'],
                    'SubVerb_Form'        : case['sub_form'],
                    'Linear_Distance'     : dsi['linear_distance'],
                    'Syntactic_Depth'     : dsi['syntactic_depth'],
                    'MDD_Sentence'        : round(mdd, 3),
                    'Target_Class'        : case['target_class'],
                })
    return rows

